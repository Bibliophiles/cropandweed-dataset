#!/usr/bin/env python3

import math
import os
import sys
import numpy as np
import optuna
from typing import Dict, Any
from pathlib import Path
from skmultilearn.model_selection import IterativeStratification
from datetime import datetime

# Add modules to path
current_dir = os.path.dirname(os.path.abspath(__file__))
parent_dir = os.path.dirname(current_dir)
data_dir = os.path.join(parent_dir, 'data')
sys.path.insert(0, data_dir)

from models.sklearn_yolo_wrapper import YOLOSklearnWrapper
from utils.logging_utils import setup_logger
from utils.reproducibility import set_seed
from stratified_split import StratifiedDataSplitter  # Keep this to reuse its data loading logic
from utils.metrics import MetricsTracker, aggregate_metrics, calculate_confidence_interval

class OptunaNestedCV:
    """
    Revised implementation of Nested Cross-Validation with Optuna using IterativeStratification.
    """
    
    def __init__(self, model_config, base_config, data_path: str, workers=None):
        self.model_config = model_config
        self.base_config = base_config
        self.data_path = data_path
        self.workers = workers or getattr(base_config, 'workers', 4)
        
        # Setup logging
        self.logger = setup_logger("optuna_nested_cv")
        
        self.logger.info(f"🔧 Initializing Optuna Nested CV")
        self.logger.info(f"   📊 Device: {base_config.get_device_string()}")
        self.logger.info(f"   🔄 Workers: {self.workers}")
        
        # ✅ FIXED: Use StratifiedDataSplitter properly
        self.stratified_splitter = StratifiedDataSplitter(
            data_path=data_path
        )

        # Load data once at initialization
        self.X, self.y_multi = self._load_dataset_info()
        
        self.logger.info(f"🎯 Nested CV initialized")
        self.logger.info(f"   📊 Dataset: {len(self.X)} samples")
        self.logger.info(f"   🏷️  Multi-label matrix: {self.y_multi.shape}")

        # ✅ ADD: Initialize metrics tracker
        self.metrics_tracker = MetricsTracker(
            output_dir=os.path.join(base_config.output_dir, "metrics")
        )
    
    def _load_dataset_info(self) -> tuple:
        """Load dataset using the stratified splitter"""
        try:
            # Use splitter's data loading method for consistency
            X_list, y_matrix = self.stratified_splitter._load_dataset_info()
            
            X = np.array(X_list)
            y_multi = np.array(y_matrix)
            
            if len(X) == 0:
                raise ValueError(f"No valid images found in {self.data_path}")
            
            self.logger.info(f"📊 Loaded {len(X)} images with multi-label annotations")
            return X, y_multi
            
        except Exception as e:
            self.logger.error(f"❌ Failed to load dataset: {e}")
            raise

    def run_nested_cv(self) -> Dict[str, Any]:
        """
        Run complete Nested Cross-Validation with Optuna using IterativeStratification.
        """
        set_seed(self.base_config.random_state, self.base_config.deterministic)
        self.logger.info("🚀 Starting Optuna Nested Cross-Validation")

        outer_scores = []
        fold_results = []
        
        # Use IterativeStratification for the outer split
        k_outer = IterativeStratification(
            n_splits=self.base_config.n_outer_folds,
        )

        # Iterating through the folds generated by scikit-multilearn
        for fold_idx, (train_val_idx, test_idx) in enumerate(k_outer.split(self.X, self.y_multi)):
            self.logger.info(f"\n📂 Outer Fold {fold_idx + 1}/{self.base_config.n_outer_folds}")

            X_train_val = self.X[train_val_idx]
            y_train_val = self.y_multi[train_val_idx]
            X_test = self.X[test_idx]
            y_test = self.y_multi[test_idx]
            
            self.logger.info(f"   📊 Train/Val: {len(X_train_val)} samples, Test: {len(X_test)} samples")
            self._log_fold_distribution(y_train_val, y_test)
            
            # INNER OPTIMIZATION: Find best hyperparameters
            best_params = self._optimize_hyperparams(X_train_val, y_train_val, fold_idx)
            
            # OUTER EVALUATION: Test best params on held-out test set
            test_score = self._evaluate_best_params(
                best_params,
                X_train_val, y_train_val, X_test, y_test, fold_idx
            )
            
            # Collect detailed fold metrics
            fold_metric = {
                'fold': fold_idx,
                'test_score': test_score,
                'best_params': best_params,
                'mAP50-95': test_score,  # Assuming test_score is mAP50-95
                'train_val_size': len(X_train_val),
                'test_size': len(X_test),
                'optimization_trials': self.base_config.n_trials
            }
            
            outer_scores.append(test_score)
            fold_results.append({
                'fold': fold_idx,
                'test_score': test_score,
                'best_params': best_params,
                'train_val_size': len(X_train_val),
                'test_size': len(X_test),
            })
            
            self.logger.info(f"✅ Outer Fold {fold_idx + 1} Score: {test_score:.4f}")
        
        mean_score = np.mean(outer_scores)
        std_score = np.std(outer_scores)
        
        # ✅ NEW: Aggregate metrics across folds
        aggregated = aggregate_metrics(fold_results)
        
        # Enhanced results with aggregated metrics
        results = {
            'mean_test_score': mean_score,
            'std_test_score': std_score,
            'individual_scores': outer_scores,
            'fold_results': fold_results,
            'aggregated_metrics': aggregated,  # ✅ NEW
            'model_name': self.model_config.model_path,
            'dataset_path': self.data_path,
            'timestamp': str(datetime.now()),
            'configuration': {
                'n_outer_folds': self.base_config.n_outer_folds,
                'n_folds': self.base_config.n_folds,
                'n_trials': self.base_config.n_trials,
                'epochs': self.base_config.epochs
            }
        }
        
        # ✅ NEW: Save experiment results
        experiment_name = f"{Path(self.model_config.model_path).stem}_{Path(self.data_path).name}"
        self.metrics_tracker.save_experiment_results(experiment_name, results)
        
        # ✅ NEW: Print comprehensive summary
        self._print_detailed_results(results)
        
        return results

    def _optimize_hyperparams(self, X_train_val: np.ndarray, y_train_val: np.ndarray, fold_idx: int):
        """Optimize hyperparameters with proper data handling"""
        
        def objective(trial):
            params = {
                'lr0': trial.suggest_float('lr0', 1e-5, 1e-1, log=True),
                'momentum': trial.suggest_float('momentum', 0.6, 0.98),
                'weight_decay': trial.suggest_float('weight_decay', 1e-6, 1e-2, log=True),
                'warmup_epochs': trial.suggest_int('warmup_epochs', 0, 5),
                'box': trial.suggest_float('box', 0.02, 0.2),
                'cls': trial.suggest_float('cls', 0.2, 4.0),
                'dfl': trial.suggest_float('dfl', 0.4, 3.0),
            }
            
            # Use IterativeStratification directly for inner CV
            from skmultilearn.model_selection import IterativeStratification
            
            k_inner = IterativeStratification(
                n_splits=self.base_config.n_folds)

            inner_scores = []
            
            # Generate inner folds using IterativeStratification
            for inner_train_idx, inner_val_idx in k_inner.split(X_train_val, y_train_val):
                if len(inner_train_idx) == 0 or len(inner_val_idx) == 0:
                    continue

                X_inner_train = X_train_val[inner_train_idx]
                X_inner_val = X_train_val[inner_val_idx]
                y_inner_train = y_train_val[inner_train_idx]
                y_inner_val = y_train_val[inner_val_idx]

                # Create estimator with proper configuration
                estimator = YOLOSklearnWrapper(
                    model_name=self.model_config.model_path,
                    epochs=min(10, self.base_config.epochs // 2),  # Reduced for speed
                    imgsz=min(320, self.model_config.input_size),
                    batch=max(4, self.model_config.get_adjusted_batch_size(self.base_config) // 2),
                    device=self.base_config.get_device_string(),
                    random_state=self.base_config.random_state + trial.number,
                    patience=5,
                    data_path=self.data_path,
                    workers=self.workers,
                    **params
                )
                
                try:
                    # Train with file lists (not matrices)
                    estimator.fit(X_inner_train.tolist(), y_inner_train, X_inner_val.tolist(), y_inner_val)
                    score = estimator.score(X_inner_val.tolist(), y_inner_val)
                    
                    # ✅ CRITICAL FIX: Ensure score is valid
                    if score is not None and isinstance(score, (int, float)) and not math.isnan(score):
                        inner_scores.append(float(score))
                    else:
                        self.logger.warning(f"Trial {trial.number} inner fold returned invalid score: {score}")
                        
                except Exception as e:
                    self.logger.warning(f"Trial {trial.number} inner fold failed: {e}")
                    continue
    
            # ✅ CRITICAL FIX: Always return a valid float
            if not inner_scores:
                self.logger.warning(f"Trial {trial.number}: No valid scores from inner folds")
                return 0.0
            
            final_score = float(np.mean(inner_scores))
            self.logger.debug(f"Trial {trial.number}: Final score = {final_score:.6f}")
            return final_score
        
        # Run Optuna optimization
        study = optuna.create_study(direction="maximize")
        study.optimize(objective, n_trials=self.base_config.n_trials, n_jobs=1)
        
        # ✅ ADD: Check if any trials completed successfully
        if len(study.trials) == 0:
            self.logger.warning("⚠️  No trials completed successfully")
            return {}
        
        completed_trials = [t for t in study.trials if t.state == optuna.trial.TrialState.COMPLETE]
        
        if not completed_trials:
            self.logger.warning(f"⚠️  No trials completed successfully out of {len(study.trials)} total trials")
            # Return default parameters
            return {
                'lr0': 0.01,
                'momentum': 0.937,
                'weight_decay': 0.0005,
                'warmup_epochs': 3,
                'box': 0.05,
                'cls': 0.5,
                'dfl': 1.5,
            }
        
        self.logger.info(f"   🎯 Best params: {study.best_params}")
        self.logger.info(f"   📈 Best score: {study.best_value:.4f}")
        self.logger.info(f"   ✅ Completed trials: {len(completed_trials)}/{len(study.trials)}")
        
        return study.best_params

    def _evaluate_best_params(self, best_params: Dict[str, Any], X_train_val: np.ndarray, 
                         y_train_val: np.ndarray, X_test: np.ndarray, y_test: np.ndarray, 
                         fold_idx: int) -> float:
        """Evaluate best parameters on test set"""
        
        self.logger.info(f"🔍 Evaluating best params on test set (fold {fold_idx})")
        
        # ✅ FIX: Create estimator with validation data for final evaluation
        final_estimator = YOLOSklearnWrapper(
            model_name=self.model_config.model_path,
            epochs=self.base_config.epochs,
            imgsz=self.model_config.input_size,
            batch=self.model_config.get_adjusted_batch_size(self.base_config),
            device=self.base_config.get_device_string(),
            random_state=self.base_config.random_state + fold_idx,
            patience=20,
            data_path=self.data_path,
            workers=self.workers,
            **best_params
        )
        
        # ✅ FIX: Provide validation data during training
        try:
            # Use a small portion of training data for validation during final training
            val_size = min(len(X_train_val) // 5, 500)  # Use 20% or max 500 images for validation
            val_indices = np.random.choice(len(X_train_val), val_size, replace=False)
            train_indices = np.setdiff1d(np.arange(len(X_train_val)), val_indices)
            
            X_final_train = X_train_val[train_indices]
            y_final_train = y_train_val[train_indices]
            X_final_val = X_train_val[val_indices]
            y_final_val = y_train_val[val_indices]
            
            # Train with validation data
            final_estimator.fit(
                X_final_train.tolist(), 
                y_final_train, 
                X_final_val.tolist(), 
                y_final_val
            )
            
            # Evaluate on test set
            test_score = final_estimator.score(X_test.tolist(), y_test)
            
            self.logger.info(f"   📊 Test score: {test_score:.4f}")
            return float(test_score)  # Ensure float return
            
        except Exception as e:
            self.logger.error(f"❌ Final evaluation failed: {e}")
            return 0.0

    def _log_fold_distribution(self, y_train_val: np.ndarray, y_test: np.ndarray):
        """Log class distribution for a multi-label fold."""
        train_counts = y_train_val.sum(axis=0)
        test_counts = y_test.sum(axis=0)
        self.logger.info(f"   📈 Train+Val class counts: {train_counts.tolist()}")
        self.logger.info(f"   📈 Test class counts: {test_counts.tolist()}")

    def _print_detailed_results(self, results):
        """Print detailed results with confidence intervals"""
        from utils.metrics import format_metrics_table, calculate_confidence_interval
        
        print("\n" + "="*80)
        print(f"🏆 EXPERIMENT COMPLETED: {results['model_name']}")
        print("="*80)
        
        # Main results
        scores = results['individual_scores']
        ci = calculate_confidence_interval(scores)
        
        print(f"📊 Cross-Validation Results:")
        print(f"   Mean mAP50-95: {ci['mean']:.4f}")
        print(f"   95% CI: [{ci['lower_bound']:.4f}, {ci['upper_bound']:.4f}]")
        print(f"   Standard Deviation: ±{np.std(scores):.4f}")
        print(f"   Individual Scores: {[f'{s:.4f}' for s in scores]}")
        
        # Configuration
        config = results['configuration']
        print(f"\n🔧 Configuration:")
        print(f"   Model: {results['model_name']}")
        print(f"   Dataset: {Path(results['dataset_path']).name}")
        print(f"   Outer Folds: {config['n_outer_folds']}")
        print(f"   Inner Folds: {config['n_folds']}")
        print(f"   Optuna Trials: {config['n_trials']}")
        print(f"   Epochs: {config['epochs']}")
        
        print("="*80)